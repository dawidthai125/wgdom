/**
 * P5.32-FIX — sync Edge WORK_RATE_PASS2_CATEGORY_URLS from local SSOT.
 * SSOT: src/lib/work-catalog/work-rate-discovery-allowlist.ts
 *       WORK_RATE_PASS2_CATEGORY_ALLOWLIST
 *
 * Usage:
 *   npx vite-node scripts/sync-work-rate-pass2-edge-from-ssot.mjs
 *   npx vite-node scripts/sync-work-rate-pass2-edge-from-ssot.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import { WORK_RATE_PASS2_CATEGORY_ALLOWLIST } from "../src/lib/work-catalog/index.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const EDGE_PATH = path.join(
  ROOT,
  "supabase/functions/make-server-0afb8820/index.tsx",
);

const BEGIN = "// BEGIN WORK_RATE_PASS2_CATEGORY_URLS (generated from SSOT — do not hand-edit)";
const END = "// END WORK_RATE_PASS2_CATEGORY_URLS";

const checkOnly = process.argv.includes("--check");

function buildEdgeMapLiteral() {
  const lines = WORK_RATE_PASS2_CATEGORY_ALLOWLIST.map((e) => {
    const key = `${e.sourceId}::${e.categoryKey}`;
    return `  ${JSON.stringify(key)}:\n    ${JSON.stringify(e.url)},`;
  });
  return [
    BEGIN,
    "const WORK_RATE_PASS2_CATEGORY_URLS: Record<string, string> = Object.freeze({",
    ...lines,
    "});",
    END,
  ].join("\n");
}

function extractEdgeMap(src) {
  const re =
    /const WORK_RATE_PASS2_CATEGORY_URLS: Record<string, string> = Object\.freeze\(\{([\s\S]*?)\}\);/;
  const m = src.match(re);
  if (!m) throw new Error("EDGE_MAP_BLOCK_NOT_FOUND");
  const body = m[1];
  const map = {};
  const pairRe = /"([^"]+)"\s*:\s*\n?\s*"([^"]+)"/g;
  let pm;
  while ((pm = pairRe.exec(body))) {
    map[pm[1]] = pm[2];
  }
  return map;
}

function ssotMap() {
  const map = {};
  for (const e of WORK_RATE_PASS2_CATEGORY_ALLOWLIST) {
    map[`${e.sourceId}::${e.categoryKey}`] = e.url;
  }
  return map;
}

function mapsEqual(a, b) {
  const ak = Object.keys(a).sort();
  const bk = Object.keys(b).sort();
  if (ak.length !== bk.length) return false;
  for (let i = 0; i < ak.length; i++) {
    if (ak[i] !== bk[i] || a[ak[i]] !== b[bk[i]]) return false;
  }
  return true;
}

const src = fs.readFileSync(EDGE_PATH, "utf8");
const edge = extractEdgeMap(src);
const local = ssotMap();

if (checkOnly) {
  if (!mapsEqual(local, edge)) {
    console.error("FAIL parity LOCAL≠EDGE");
    console.error("local", Object.keys(local).sort());
    console.error("edge", Object.keys(edge).sort());
    process.exit(1);
  }
  console.log("PASS parity", Object.keys(local).length, "keys");
  process.exit(0);
}

const generated = buildEdgeMapLiteral();

let next;
if (src.includes(BEGIN) && src.includes(END)) {
  next = src.replace(
    new RegExp(`${BEGIN}[\\s\\S]*?${END}`),
    generated,
  );
} else {
  const re =
    /\/\*\*\s*\n \* PASS2 Owner category allowlist[\s\S]*?const WORK_RATE_PASS2_CATEGORY_URLS: Record<string, string> = Object\.freeze\(\{[\s\S]*?\}\);/;
  if (!re.test(src)) {
    console.error("FAIL cannot locate Edge allowlist block to replace");
    process.exit(1);
  }
  const header = `/**
 * PASS2 Owner category allowlist — mirrors WORK_RATE_PASS2_CATEGORY_ALLOWLIST (src SSOT).
 * Generated by scripts/sync-work-rate-pass2-edge-from-ssot.mjs — do not hand-edit the map.
 * Key: \`\${sourceId}::\${categoryKey}\` → https URL on allowlisted host only.
 */
`;
  next = src.replace(re, header + generated);
}

if (next === src && mapsEqual(local, edge)) {
  console.log("OK already in sync", Object.keys(local).length, "keys");
  process.exit(0);
}

fs.writeFileSync(EDGE_PATH, next, "utf8");
const verify = extractEdgeMap(fs.readFileSync(EDGE_PATH, "utf8"));
if (!mapsEqual(local, verify)) {
  console.error("FAIL write verify LOCAL≠EDGE after sync");
  process.exit(1);
}
console.log(
  "SYNCED Edge PASS2 keys",
  Object.keys(verify).sort().join(", "),
);
console.log("count", Object.keys(verify).length);
